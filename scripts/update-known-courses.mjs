#!/usr/bin/env node
/** Refresh the offline OCR dictionary from the current official course catalogue. */
import { renameSync, writeFileSync } from 'node:fs';
import { get } from './fjfi-fetch.mjs';
import { parseCourseCatalogue } from './fjfi-metadata.mjs';

const source = 'https://bilakniha.cvut.cz/cs/f4-predmety.html';
const { academicYear, codes } = parseCourseCatalogue((await get(source)).data.toString('utf8'));
const output = new URL('../src/import/known-courses.ts', import.meta.url);
const temporary = new URL('../src/import/known-courses.ts.tmp', import.meta.url);
writeFileSync(temporary, `// Generated by scripts/update-known-courses.mjs from ${source} — do not edit by hand.
// Academic year ${academicYear}; generated on ${new Date().toISOString().slice(0, 10)}.

/** Full codes of currently offered regular courses; the first two digits identify the department. */
export const KNOWN_COURSES: readonly string[] = [
${codes.map((code) => `  ${JSON.stringify(code)},`).join('\n')}
];
`);
renameSync(temporary, output);
console.log(`${codes.length} course codes for ${academicYear} → src/import/known-courses.ts`);
